/* ============================================================================
 * "Bring your own AI" engine.
 *
 * The user's assistant (Claude or ChatGPT, connected over MCP) does the
 * generation. This module turns the shared pipeline into a step machine:
 *   get_next_step → the assistant does the task → submit_* → next step …
 * Server-only steps (metadata, transcript, finalize) run here automatically.
 * Every submission is validated with the same Zod schemas and `apply*`
 * functions the background engine uses, including coverage enforcement.
 * ==========================================================================*/

export type SubmitTool =
  | "submit_chunk_analysis"
  | "submit_frame_analysis"
  | "submit_course_overview"
  | "submit_curriculum"
  | "submit_lesson"
  | "submit_illustrations"
  | "submit_quiz"
  | "submit_quality_review";

export type Progress = { stage: string; percent: number; completed_tasks: number; total_tasks: number };

export type NextStep =
  | {
      kind: "task";
      courseId: string;
      progress: Progress;
      taskKey: string;
      tool: SubmitTool;
      args: Record<string, string | number>;
      title: string;
      prompt: Prompt;
    }
  | { kind: "wait"; courseId: string; progress: Progress; reason: string; retryAfterSeconds: number }
  | { kind: "done"; courseId: string; progress: Progress; courseUrl: string; status: string; title: string }
  | { kind: "failed"; courseId: string; error: string };

const MAX_STRICT_ATTEMPTS = 2; // after this, coverage gaps are accepted and flagged instead of rejected

export class AssistantError extends Error {}

function makeCtx(job: JobRow): Ctx {
  const db = createAdminClient();
  return {
    job,
    db,
    memo: new Map(),
    ai: () => Promise.reject(new AiNotConfiguredError()), // never used: the user's assistant is the model
    log: async (level, message, data) => {
      await db.from("job_logs").insert({ job_id: job.id, level, message, data: data ?? null });
    },
  };
}

/** Loads the course's active assistant job, verifying ownership. */
export async function loadAssistantJob(userId: string, courseId: string): Promise<Ctx> {
  const db = createAdminClient();
  const { data: course } = await db.from("courses").select("id, user_id").eq("id", courseId).maybeSingle();
  if (!course || course.user_id !== userId) throw new AssistantError("Course not found in your account.");
  const { data: job } = await db
    .from("course_generation_jobs")
    .select("id, user_id, course_id, job_type, status, input, state, current_stage")
    .eq("course_id", courseId)
    .eq("job_type", ASSISTANT_JOB)
    .order("created_at", { ascending: false })
    .limit(1)
    .maybeSingle();
  if (!job) {
    throw new AssistantError(
      "This course is not being generated by your assistant (it uses the background engine or is already finished).",
    );
  }
  const row = job as JobRow;
  row.state = row.state ?? {};
  row.state.stagesDone ??= [];
  row.state.planned ??= [];
  return makeCtx(row);
}

async function saveJob(ctx: Ctx, patch: Record<string, unknown> = {}) {
  await ctx.db.from("course_generation_jobs").update({ state: ctx.job.state, ...patch }).eq("id", ctx.job.id);
}

async function progress(ctx: Ctx, stage: StageKey | null): Promise<Progress> {
  await updateProgress(ctx.job.id, ctx.job.status === "completed");
  const { data } = await ctx.db
    .from("course_generation_jobs")
    .select("progress, completed_tasks, total_tasks")
    .eq("id", ctx.job.id)
    .single();
  return {
    stage: stage ? STAGE_LABELS[stage] : "Done",
    percent: data?.progress ?? 0,
    completed_tasks: data?.completed_tasks ?? 0,
    total_tasks: data?.total_tasks ?? 0,
  };
}

const TOOL_FOR: Record<string, SubmitTool> = {
  analyze: "submit_chunk_analysis",
  frame: "submit_frame_analysis",
  overview: "submit_course_overview",
  curriculum: "submit_curriculum",
  lesson: "submit_lesson",
  illustrations: "submit_illustrations",
  quiz: "submit_quiz",
  qa: "submit_quality_review",
};

/** Builds the brief for an assistant task, or null when the task can be skipped. */
async function briefFor(ctx: Ctx, task: TaskRow): Promise<{ title: string; prompt: Prompt; args: Record<string, string | number> } | null> {
  const [kind, id] = task.task_key.split(":");
  const p = task.payload;
  switch (kind) {
    case "analyze": {
      const index = Number(p.index);
      const { data: src } = await ctx.db.from("courses").select("source_type").eq("id", ctx.job.course_id).single();
      return {
        title: src?.source_type === "prompt" ? "Plan the course syllabus from the creator's brief" : `Analyze source window ${index + 1} of ${p.total}`,
        args: { chunk_index: index },
        prompt: await buildChunkPrompt(ctx, index),
      };
    }
    case "frame": {
      const prompt = await buildFramePrompt(ctx, id);
      return prompt ? { title: "Describe a screenshot from the video", args: { frame_id: id }, prompt } : null;
    }
    case "overview":
      return { title: "Write the course overview", args: {}, prompt: await buildOverviewPrompt(ctx) };
    case "curriculum":
      return { title: "Design the curriculum", args: {}, prompt: await buildCurriculumPrompt(ctx) };
    case "lesson": {
      const brief = await buildLessonPrompt(ctx, id);
      return brief ? { title: `Write lesson: ${brief.title}`, args: { lesson_id: id }, prompt: brief } : null;
    }
    case "illustrations": {
      const prompt = await buildIllustrationsPrompt(ctx, id);
      return prompt ? { title: "Design illustrations for a lesson", args: { lesson_id: id }, prompt } : null;
    }
    case "quiz": {
      const brief = await buildQuizPrompt(ctx, p);
      return brief
        ? { title: brief.isFinal ? "Write the final assessment" : "Write a module quiz", args: { quiz_key: id }, prompt: brief.prompt }
        : null;
    }
    case "qa":
      return { title: "Review course quality", args: {}, prompt: (await buildQualityPrompt(ctx)).prompt };
  }
  return null;
}

/**
 * Advances the job as far as the server can on its own and returns what the
 * assistant should do next.
 */
export async function nextStep(ctx: Ctx): Promise<NextStep> {
  const courseId = ctx.job.course_id;
  const stages = JOB_STAGES[ctx.job.job_type];
  try {
    for (let guard = 0; guard < 50; guard++) {
      const { data: fresh } = await ctx.db.from("course_generation_jobs").select("status, state").eq("id", ctx.job.id).single();
      if (fresh?.status === "cancelled") return { kind: "failed", courseId, error: "Generation was cancelled." };
      if (fresh?.status === "failed") {
        const { data: j } = await ctx.db.from("course_generation_jobs").select("error_message").eq("id", ctx.job.id).single();
        return { kind: "failed", courseId, error: j?.error_message ?? "Generation failed." };
      }
      if (fresh?.state) {
        ctx.job.state = { ...fresh.state, stagesDone: fresh.state.stagesDone ?? [], planned: fresh.state.planned ?? [] };
      }

      const stage = stages.find((s) => !ctx.job.state.stagesDone!.includes(s));
      if (!stage) return await complete(ctx);

      if (!ctx.job.state.planned!.includes(stage)) {
        const specs = await planStage(stage, ctx);
        if (specs.length) {
          await ctx.db.from("job_tasks").upsert(
            specs.map((s, i) => ({ job_id: ctx.job.id, stage, task_key: s.key, payload: s.payload ?? {}, position: s.position ?? i })),
            { onConflict: "job_id,task_key", ignoreDuplicates: true },
          );
        }
        ctx.job.state.planned!.push(stage);
        ctx.job.status = "running";
        await saveJob(ctx, { current_stage: stage, status: "running", started_at: new Date().toISOString() });
      }

      const { data: taskData } = await ctx.db
        .from("job_tasks")
        .select("*")
        .eq("job_id", ctx.job.id)
        .eq("stage", stage)
        .order("position");
      const tasks = (taskData ?? []) as TaskRow[];
      const open = tasks.filter((t) => !["completed", "skipped"].includes(t.status));
      if (!open.length) {
        ctx.job.state.stagesDone!.push(stage);
        await saveJob(ctx);
        continue;
      }

      const task = open[0];
      if (isServerTask(task.task_key)) {
        if (task.status === "waiting") {
          const at = Number((task.payload as { retryAt?: number }).retryAt ?? 0);
          if (at > Date.now()) {
            return {
              kind: "wait",
              courseId,
              progress: await progress(ctx, stage),
              reason: "The transcript is still being prepared by the transcription service.",
              retryAfterSeconds: Math.ceil((at - Date.now()) / 1000),
            };
          }
        }
        const res = await runTask(task, ctx);
        if (res.status === "waiting") {
          await ctx.db
            .from("job_tasks")
            .update({ status: "waiting", result: res.result ?? null, payload: { ...task.payload, retryAt: Date.now() + res.retryAfterSeconds * 1000 } })
            .eq("id", task.id);
          await saveJob(ctx);
          return {
            kind: "wait",
            courseId,
            progress: await progress(ctx, stage),
            reason: "The transcript is still being prepared by the transcription service.",
            retryAfterSeconds: res.retryAfterSeconds,
          };
        }
        await ctx.db.from("job_tasks").update({ status: res.status, result: res.result ?? null, attempts: task.attempts + 1 }).eq("id", task.id);
        await saveJob(ctx); // persists state such as hasTimestamps
        continue;
      }

      const raw = await briefFor(ctx, task);
      const brief = raw ? { ...raw, prompt: await adaptPromptForCourse(ctx, raw.prompt) } : null;
      if (!brief) {
        await ctx.db.from("job_tasks").update({ status: "skipped" }).eq("id", task.id);
        continue;
      }
      return {
        kind: "task",
        courseId,
        progress: await progress(ctx, stage),
        taskKey: task.task_key,
        tool: TOOL_FOR[task.task_key.split(":")[0]],
        args: brief.args,
        title: brief.title,
        prompt: brief.prompt,
      };
    }
    throw new Error("Could not determine the next step.");
  } catch (err) {
    if (err instanceof RetryableError) {
      return { kind: "wait", courseId, progress: await progress(ctx, null), reason: err.message, retryAfterSeconds: err.retryAfterSeconds };
    }
    if (err instanceof FatalJobError || err instanceof VideoNotFoundError) {
      await ctx.log("error", "Job failed", { error: err.message });
      await saveJob(ctx, { status: "failed", error_message: err.message, completed_at: new Date().toISOString() });
      await ctx.db.from("courses").update({ status: "failed" }).eq("id", courseId);
      return { kind: "failed", courseId, error: err.message };
    }
    throw err;
  }
}

async function complete(ctx: Ctx): Promise<NextStep> {
  ctx.job.status = "completed";
  await saveJob(ctx, { status: "completed", progress: 100, completed_at: new Date().toISOString(), current_stage: "save" });
  const { data: course } = await ctx.db.from("courses").select("title, status").eq("id", ctx.job.course_id).single();
  return {
    kind: "done",
    courseId: ctx.job.course_id,
    progress: await progress(ctx, null),
    courseUrl: `${publicEnv.siteUrl}/dashboard/courses/${ctx.job.course_id}`,
    status: course?.status ?? "ready",
    title: course?.title ?? "Your course",
  };
}

/* ============================================================================
 * Submissions
 * ==========================================================================*/

export type SubmitResult =
  | { ok: true; next: NextStep; note?: string }
  | { ok: false; error: string; missing?: { id: string; title: string }[]; acceptedNextTime: boolean };

async function findTask(ctx: Ctx, taskKey: string): Promise<TaskRow> {
  const { data } = await ctx.db.from("job_tasks").select("*").eq("job_id", ctx.job.id).eq("task_key", taskKey).maybeSingle();
  if (!data) {
    throw new AssistantError(
      `That item isn't ready to be submitted yet (${taskKey}). Call get_next_step to see what the course needs next.`,
    );
  }
  return data as TaskRow;
}

/** Validates and saves one assistant submission, then returns the next step. */
export async function submit<S extends z.ZodType>(
  ctx: Ctx,
  taskKey: string,
  schema: S,
  raw: unknown,
  apply: (data: z.infer<S>, strict: boolean) => Promise<unknown>,
): Promise<SubmitResult> {
  const task = await findTask(ctx, taskKey);
  const parsed = schema.safeParse(raw);
  if (!parsed.success) {
    return { ok: false, error: `Invalid submission: ${parsed.error.message.slice(0, 1500)}`, acceptedNextTime: false };
  }
  const strict = task.attempts < MAX_STRICT_ATTEMPTS;
  try {
    const result = await apply(parsed.data, strict);
    await ctx.db.from("job_tasks").update({ status: "completed", result, error: null, attempts: task.attempts + 1 }).eq("id", task.id);
    const note =
      !strict && result && typeof result === "object" && "missing" in result && Array.isArray(result.missing) && result.missing.length
        ? "Saved, but some assigned teaching points are still not covered; the lesson is flagged for review."
        : undefined;
    return { ok: true, next: await nextStep(ctx), note };
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    await ctx.db.from("job_tasks").update({ status: "failed", error: message.slice(0, 2000), attempts: task.attempts + 1 }).eq("id", task.id);
    if (err instanceof CoverageError) {
      return { ok: false, error: message, missing: err.missing, acceptedNextTime: task.attempts + 1 >= MAX_STRICT_ATTEMPTS };
    }
    if (err instanceof FatalJobError) throw err;
    return { ok: false, error: message, acceptedNextTime: false };
  }
}

/* Typed wrappers used by the MCP tools. */
export const submitters = {
  chunk: (ctx: Ctx, index: number, analysis: unknown) =>
    submit(ctx, `analyze:${index}`, ChunkAnalysis, analysis, (d) => applyChunkAnalysis(ctx, index, d)),
  frame: (ctx: Ctx, frameId: string, analysis: unknown) =>
    submit(ctx, `frame:${frameId}`, FrameAnalysis, analysis, (d) => applyFrameAnalysis(ctx, frameId, d)),
  overview: (ctx: Ctx, overview: unknown) => submit(ctx, "overview", CourseOverview, overview, (d) => applyOverview(ctx, d)),
  curriculum: (ctx: Ctx, curriculum: unknown) =>
    submit(ctx, "curriculum", Curriculum, curriculum, (d, strict) => applyCurriculum(ctx, d, { strict })),
  lesson: (ctx: Ctx, lessonId: string, lesson: unknown) =>
    submit(ctx, `lesson:${lessonId}`, LessonContent, lesson, (d, strict) => applyLesson(ctx, lessonId, d, { strict })),
  illustrations: (ctx: Ctx, lessonId: string, set: unknown) =>
    submit(ctx, `illustrations:${lessonId}`, IllustrationSet, set, (d) => applyIllustrations(ctx, lessonId, d)),
  quiz: async (ctx: Ctx, quizKey: string, quiz: unknown) => {
    const task = await findTask(ctx, `quiz:${quizKey}`);
    return submit(ctx, `quiz:${quizKey}`, QuizSpec, quiz, (d) => applyQuiz(ctx, task.payload, d));
  },
  quality: (ctx: Ctx, review: unknown) => submit(ctx, "qa", QualityReview, review, (d) => applyQuality(ctx, d)),
};
